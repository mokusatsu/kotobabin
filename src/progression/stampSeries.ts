const series: StampSeries[] = [];
interface SeriesOptions {
  repeatable?: boolean;
  scope?: StampScope;
}
function add(
  category: SeriesCategory, id: string, name: string, targets: readonly number[], unit: string,
  condition: (target: number) => string, scenes: readonly string[], options: SeriesOptions = {},
): void {
  const scope = options.scope ?? (category === 'city' ? '街' : '通常');
  const hidden = category === 'secret';
  const tierNames = options.repeatable ? STAMP_RANKS : targets.length === 1
    ? [name]
    : TIER_NAMES[id] ?? TIER_NAMES[id.slice(0, id.lastIndexOf('_'))];
  if (tierNames?.length !== targets.length) throw new Error(`Missing tier names for ${id}`);
  series.push({
    id, name, category, repeatable: options.repeatable ?? false,
    stamps: targets.map((target, index) => {
      const tierLabel = tierNames[index];
      const stampId = `series-${id}-${target}`;
      return {
        id: stampId,
        name: targets.length === 1 ? name : `${name}・${tierLabel}`,
        condition: condition(target),
        flavor_text: scenes[index],
        scope, hidden, hidden_hint: null,
        stamp_asset_id: `stamp_series_${id}_${target}`,
        title_id: `title_${stampId}`,
        seriesId: id,
        target, unit, tierLabel,
      };
    }),
  });
}

